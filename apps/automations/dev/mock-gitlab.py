MERGE_REQUEST = {
    "iid": 1,
    "title": f"chore(deps): update helm release loki to v{new} (mock)",
    "description": DESCRIPTION,
    "state": "opened",
    "source_branch": f"renovate/loki-{match[2]}.x",
    "target_branch": "pre",
    "sha": "4f1c0ffee0000000000000000000000000000000",
    "web_url": "http://localhost/vinnel-cloud/gaia/-/merge_requests/1",
    "labels": [],
    "author": RENOVATE,
}
DIFFS = [{"old_path": TARGET, "new_path": TARGET, "diff": unified_diff(), "new_file": False, "renamed_file": False, "deleted_file": False}]
NOTES = []


class Handler(BaseHTTPRequestHandler):
    def reply(self, status, body, content_type="application/json"):
        data = body if isinstance(body, bytes) else json.dumps(body).encode()
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def authorized(self):
        if self.headers.get("PRIVATE-TOKEN") == TOKEN:
            return True
        self.reply(401, {"message": "401 Unauthorized"})
        return False

    def body(self):
        return json.loads(self.rfile.read(int(self.headers.get("Content-Length", 0))) or b"{}")

    def do_GET(self):
        if not self.authorized():
            return
        path = urlsplit(self.path).path
        if path == "/api/v4/user":
            return self.reply(200, SELF)
        if path == MR_PATH:
            return self.reply(200, MERGE_REQUEST)
        if path == MR_PATH + "/diffs":
            return self.reply(200, DIFFS)
        if path == MR_PATH + "/notes":
            return self.reply(200, NOTES)
        if path.startswith(FILES_PREFIX) and path.endswith("/raw"):
            name = unquote(path[len(FILES_PREFIX) : -len("/raw")])
            if name == TARGET:
                return self.reply(200, updated.encode(), "text/plain")
            if name in TRACKED:
                return self.reply(200, (ROOT / name).read_bytes(), "text/plain")
        self.reply(404, {"message": "404 Not Found"})

    def do_POST(self):
        if not self.authorized():
            return
        if urlsplit(self.path).path != MR_PATH + "/notes":
            return self.reply(404, {"message": "404 Not Found"})
        note = {"id": len(NOTES) + 1, "body": self.body().get("body", ""), "system": False, "author": SELF}
        NOTES.append(note)
        self.reply(201, note)

    def do_PUT(self):
        if not self.authorized():
            return
        path = urlsplit(self.path).path
        for note in NOTES:
            if path == f"{MR_PATH}/notes/{note['id']}":
                note["body"] = self.body().get("body", "")
                return self.reply(200, note)
        self.reply(404, {"message": "404 Not Found"})

    def log_message(self, fmt, *args):
        print(f"{self.command} {urlsplit(self.path).path} -> {args[1]}", flush=True)


ThreadingHTTPServer(("", PORT), Handler).serve_forever()
